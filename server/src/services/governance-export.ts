/**
 * Generates combined single-file Markdown bundle.
 */
export function exportCombinedMarkdown(
  projectName: string,
  documents: Record<string, { title: string; fileName: string; content: string }>,
): string {
  const parts: string[] = [
    `# Complete Project Governance Pack: ${projectName}`,
    `*Generated by Project Auro autonomous governance control plane*\n`,
    `---\n`,
  ];

  for (const [kind, doc] of Object.entries(documents)) {
    parts.push(`<!-- START DOCUMENT: ${doc.fileName} (${kind}) -->`);
    parts.push(doc.content.trim());
    parts.push(`\n---\n`);
  }

  return parts.join("\n");
}

/**
 * Escapes CSV values with double quotes and comma handling.
 */
function escapeCsv(value: string | number | undefined | null): string {
  if (value === undefined || value === null) return '""';
  const str = String(value).replace(/"/g, '""');
  return `"${str}"`;
}

/**
 * Generates Standard Sprint Backlog CSV.
 */
export function exportSprintBacklogCsv(stories: SprintStoryItem[] = DEFAULT_SPRINT_STORIES): string {
  const headers = [
    "ID",
    "Epic",
    "Summary",
    "Issue Type",
    "Priority",
    "Story Points",
    "Assignee Role",
    "Depends On",
    "Description",
    "Acceptance Criteria",
  ];

  const rows = [headers.join(",")];

  for (const story of stories) {
    const row = [
      escapeCsv(story.id),
      escapeCsv(story.epic),
      escapeCsv(story.summary),
      escapeCsv(story.issueType),
      escapeCsv(story.priority),
      story.storyPoints,
      escapeCsv(story.assigneeRole),
      escapeCsv(story.dependsOn || "None"),
      escapeCsv(story.description),
      escapeCsv(story.acceptanceCriteria),
    ];
    rows.push(row.join(","));
  }

  return rows.join("\n");
}

